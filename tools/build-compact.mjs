// Expands tools/compact.tpl.css (the ≤1279 layout from the mobile Figma frame
// 80:969, 360 wide) into css/media.css between
//   /* compact:generated:start */ … /* compact:generated:end */
// Run by `npm run build:css` before the laptop generator.
//
// Every Figma mobile value is scaled by --m (set per breakpoint in media.css).
// Directives (each on a line of its own):
//   @sec <y>        origin for T() = the section's top in the Figma frame;
//                   L()/R() are positions in the centred 360 × --m column
//   @card <x> <y>   origin for elements inside a card: T() from the card's top,
//                   L() from its left edge (no centring)
//   @end            back to the enclosing @sec
// Macros:
//   T(y)   top:   (y − origin y) × --m
//   L(x)   left:  column: calc(50% + (x − 180) × --m)   card: (x − origin x) × --m
//   R(x)   right of an element whose right edge is at x: calc(50% − (x − 180) × --m)
//   M(n)   n × --m (sizes, fonts, gaps)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TPL = path.join(ROOT, 'tools/compact.tpl.css');
const MEDIA = path.join(ROOT, 'css/media.css');
const START = '/* compact:generated:start */';
const END = '/* compact:generated:end */';

const num = (n) => +(+n).toFixed(3);
const m = (n) => (num(n) === 0 ? '0' : `calc(${num(n)}px * var(--m))`);
const offset = (d) => (num(d) === 0 ? '50%' : `calc(50% ${d < 0 ? '-' : '+'} ${Math.abs(num(d))}px * var(--m))`);

let sec = null;
let card = null;
const out = [];
readFileSync(TPL, 'utf8').split('\n').forEach((line, i) => {
  const d = line.trim().match(/^@(sec|card|end)\b\s*(.*)$/);
  if (d) {
    const args = d[2].split(/\s+/).filter(Boolean).map(Number);
    if (d[1] === 'sec') { sec = args[0]; card = null; }
    if (d[1] === 'card') card = { x: args[0], y: args[1] };
    if (d[1] === 'end') card = null;
    return;
  }
  out.push(line
    .replace(/\bT\((-?[\d.]+)\)/g, (_, y) => {
      const o = card ? card.y : sec;
      if (o === null) throw new Error(`T() before @sec on line ${i + 1}`);
      return m(y - o);
    })
    .replace(/\bL\((-?[\d.]+)\)/g, (_, x) => (card ? m(x - card.x) : offset(x - 180)))
    .replace(/\bR\((-?[\d.]+)\)/g, (_, x) => (card ? m(card.x + 320 - x) : offset(180 - x)))
    .replace(/\bM\((-?[\d.]+)\)/g, (_, n) => m(n)));
});

const block = `${START}\n/* Generated by tools/build-compact.mjs from tools/compact.tpl.css. Do not edit by hand. */\n${out.join('\n').trim()}\n${END}`;
const media = readFileSync(MEDIA, 'utf8');
const a = media.indexOf(START);
const b = media.indexOf(END);
if (a === -1 || b === -1) throw new Error('compact markers not found in css/media.css');
writeFileSync(MEDIA, media.slice(0, a) + block + media.slice(b + END.length));
console.log('compact block regenerated');
